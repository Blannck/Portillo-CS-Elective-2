-- 4.1 ROLES POLICIES
-- Signed out: No access
-- Customer: Read
-- Admin: Read
CREATE POLICY "roles_select_authenticated"
ON public.roles
FOR SELECT
TO authenticated
USING (true);

-- 4.2 PROFILES POLICIES
-- Signed out: No access
-- Customer: Read own row only
-- Admin: Read all profiles
CREATE POLICY "profiles_select"
ON public.profiles
FOR SELECT
TO authenticated
USING (
  id = auth.uid() OR public.is_admin()
);

-- Customer: Update own row only, and NEVER the role
CREATE POLICY "profiles_update_own"
ON public.profiles
FOR UPDATE
TO authenticated
USING (id = auth.uid())
WITH CHECK (
  id = auth.uid() AND
  role_id = (SELECT p.role_id FROM public.profiles p WHERE p.id = auth.uid())
);

-- Admin: Can update any profile
CREATE POLICY "profiles_update_admin"
ON public.profiles
FOR UPDATE
TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

