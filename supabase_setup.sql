-- 1. Create the products table
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  price NUMERIC NOT NULL,
  category_id INT DEFAULT 1,
  stock INT DEFAULT 10,
  image_url TEXT,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Enable Row Level Security (RLS) as covered in Slide 30 & 41
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;

-- 3. Create RLS Policies for Select, Insert, Update, and Delete
DROP POLICY IF EXISTS "Allow public read access" ON public.products;
CREATE POLICY "Allow public read access" 
ON public.products 
FOR SELECT 
USING (true);

DROP POLICY IF EXISTS "Allow public insert" ON public.products;
CREATE POLICY "Allow public insert" 
ON public.products 
FOR INSERT 
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update" ON public.products;
CREATE POLICY "Allow public update" 
ON public.products 
FOR UPDATE 
USING (true);

DROP POLICY IF EXISTS "Allow public delete" ON public.products;
CREATE POLICY "Allow public delete" 
ON public.products 
FOR DELETE 
USING (true);

