-- 3.1 FUNCTION: handle_new_user (Auto-populates public.profiles on signup)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_role_id BIGINT;
BEGIN
  -- Obtain customer role ID
  SELECT id INTO v_role_id FROM public.roles WHERE role = 'customer' LIMIT 1;

  -- Fallback if roles table is empty
  IF v_role_id IS NULL THEN
    INSERT INTO public.roles (role) VALUES ('customer') RETURNING id INTO v_role_id;
  END IF;

  INSERT INTO public.profiles (id, email, firstname, lastname, role_id)
  VALUES (
    new.id,
    new.email,
    COALESCE(new.raw_user_meta_data->>'firstname', 'Player'),
    COALESCE(new.raw_user_meta_data->>'lastname', ''),
    v_role_id
  )
  ON CONFLICT (id) DO UPDATE
  SET email = EXCLUDED.email,
      firstname = COALESCE(EXCLUDED.firstname, public.profiles.firstname),
      lastname = COALESCE(EXCLUDED.lastname, public.profiles.lastname);

  RETURN new;
EXCEPTION
  WHEN OTHERS THEN
    -- Ensure user creation in auth.users is never blocked
    RETURN new;
END;
$$;

-- TRIGGER: Attach handle_new_user to auth.users table
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();

-- 3.2 FUNCTION: is_admin (Checks if current user has admin role)
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1
    FROM public.profiles p
    JOIN public.roles r ON r.id = p.role_id
    WHERE p.id = auth.uid() AND r.role = 'admin'
  );
END;
$$;

-- 3.3 FUNCTION: create_order (Atomic transactional checkout with DB verification & stock deduction)
-- Fulfills requirement:
-- - Prices, product names, and stock checks come from database at checkout time.
-- - Stock is reduced by ordered quantities in the same transaction.
-- - Saves order + order items together or rolls back completely if anything fails.
CREATE OR REPLACE FUNCTION public.create_order(items JSONB)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id UUID;
  v_order_id BIGINT;
  v_calc_total NUMERIC(10,2) := 0.00;
  v_item RECORD;
  v_prod RECORD;
BEGIN
  -- 1. Ensure user is authenticated
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'User must be authenticated to place an order.';
  END IF;

  -- 2. Validate items payload
  IF items IS NULL OR jsonb_array_length(items) = 0 THEN
    RAISE EXCEPTION 'Order must contain at least one item.';
  END IF;

  -- 3. First pass: Lock product rows, check stocks, and calculate authoritative total
  FOR v_item IN SELECT * FROM jsonb_to_recordset(items) AS x(product_id BIGINT, quantity BIGINT)
  LOOP
    IF v_item.quantity <= 0 THEN
      RAISE EXCEPTION 'Item quantity must be greater than zero for product ID %', v_item.product_id;
    END IF;

    -- Lock row FOR UPDATE to prevent race conditions during checkout
    SELECT id, name, price, stock
    INTO v_prod
    FROM public.products
    WHERE id = v_item.product_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product with ID % does not exist.', v_item.product_id;
    END IF;

    IF v_prod.stock < v_item.quantity THEN
      RAISE EXCEPTION 'Insufficient stock for "%". Available: %, Requested: %',
        v_prod.name, v_prod.stock, v_item.quantity;
    END IF;

    -- Add to total using authoritative database price
    v_calc_total := v_calc_total + (v_prod.price::NUMERIC * v_item.quantity);
  END LOOP;

  -- 4. Create Order Record
  INSERT INTO public.orders (user_id, status, total)
  VALUES (v_user_id, 'completed', v_calc_total)
  RETURNING id INTO v_order_id;

  -- 5. Second pass: Deduct stock and insert Order Items snapshot
  FOR v_item IN SELECT * FROM jsonb_to_recordset(items) AS x(product_id BIGINT, quantity BIGINT)
  LOOP
    SELECT price INTO v_prod FROM public.products WHERE id = v_item.product_id;

    -- Reduce stock
    UPDATE public.products
    SET stock = stock - v_item.quantity
    WHERE id = v_item.product_id;

    -- Record snapshot of unit price paid
    INSERT INTO public.order_items (order_id, product_id, unit_price, quantity)
    VALUES (v_order_id, v_item.product_id, v_prod.price::NUMERIC, v_item.quantity);
  END LOOP;

  -- Return created order summary
  RETURN jsonb_build_object(
    'order_id', v_order_id,
    'total', v_calc_total,
    'status', 'completed'
  );
END;
$$;

