  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role VARCHAR NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  encoded_by UUID REFERENCES auth.users(id) ON DELETE SET NULL
